//! Compile-time article store. Until the editorial CMS (WS2) wires a database,
//! published articles live here as data. An article may carry a self-hosted
//! `video` (drives the on-page player + og:video for inline social play) and/or
//! a `youtube` id (privacy-respecting youtube-nocookie embed) plus an `image`
//! (hero/thumbnail; for video pieces this is the video's thumbnail).

/// A self-hosted video attached to an article (served from /media; drives the
/// player + Open Graph video tags for rich social sharing).
#[derive(Clone, PartialEq)]
pub struct Video {
    pub mp4: &'static str,    // e.g. "/media/<slug>.mp4"
    pub poster: &'static str, // e.g. "/media/<slug>.jpg"
    pub width: u32,
    pub height: u32,
    pub duration_secs: u32,
}

#[derive(Clone, PartialEq)]
pub struct Article {
    pub slug: &'static str,
    pub title: &'static str,
    pub summary: &'static str,
    pub byline: &'static str,
    pub date: &'static str,            // human, e.g. "June 2026"
    pub iso_date: &'static str,        // for <time>/JSON-LD, e.g. "2026-06-14"
    pub kind: &'static str,            // "Court report" | "Investigation" | "Announcement" | "Explainer"
    pub body: &'static [&'static str], // paragraphs
    pub video: Option<Video>,          // self-hosted video (og:video inline play)
    pub youtube: Option<&'static str>, // youtube id → youtube-nocookie embed
    pub image: Option<&'static str>,   // hero/thumbnail (absolute URL or /path)
}

impl Article {
    /// On-site hero/thumbnail used in lists + at the top of the article.
    pub fn hero(&self) -> Option<&'static str> {
        self.image
    }
    /// Branded share card for Open Graph (generated by tools/og/gen.mjs).
    pub fn og_image(&self) -> String {
        format!("/og/news/{}.png", self.slug)
    }
}

